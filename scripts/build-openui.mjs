// Prepares OpenUI generative UI for the final chat (the future self). Run after changing the OpenUI packages
// or the allowed components:  npm run build:openui
// - copies the prebuilt OpenUI renderer (React + the OpenUI chat components) into public/vendor/openui/
// - writes lib/openui-prompt.mjs: the OpenUI Lang rules for the allowed components, for the twin's system prompt.
// The app itself loads nothing from node_modules, so `npm start` keeps working without an install.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { createLibrary } from '@openuidev/react-lang';
import { openuiChatLibrary } from '@openuidev/react-ui/genui-lib';
import { OPENUI_COMPONENTS } from '../lib/openui-components.mjs';

const root = new URL('../', import.meta.url);
const require = createRequire(import.meta.url);

// 1. The renderer, served from our own origin (the page's Content Security Policy allows no CDNs).
const bundleDir = dirname(require.resolve('@openuidev/browser-bundle/package.json'));
const vendor = new URL('public/vendor/openui/', root);
await mkdir(vendor, { recursive: true });
await copyFile(`${bundleDir}/dist/openui-bundle.min.js`, new URL('openui-bundle.min.js', vendor));
await copyFile(`${bundleDir}/dist/openui-styles.css`, new URL('openui-styles.css', vendor));
await copyFile(`${bundleDir}/LICENSE`, new URL('LICENSE', vendor));

// 2. The language rules, generated from the same component definitions the renderer uses.
const missing = OPENUI_COMPONENTS.filter(name => !openuiChatLibrary.components[name]);
if (missing.length) throw new Error(`Unknown OpenUI components: ${missing.join(', ')}`);
const library = createLibrary({ root: 'Card', components: OPENUI_COMPONENTS.map(name => openuiChatLibrary.components[name]) });
const rules = library.prompt({})
  // The stock opening says the whole reply is OpenUI Lang; here it is one optional block inside a spoken reply.
  .replace(/^You are an AI assistant[^\n]*\n+/, '')
  .trim();
await writeFile(new URL('lib/openui-prompt.mjs', root),
  `// Generated by scripts/build-openui.mjs from @openuidev/react-ui ${JSON.parse(await readFile(new URL('node_modules/@openuidev/react-ui/package.json', root))).version}. Do not edit.\n` +
  `export const OPENUI_LANG_RULES = ${JSON.stringify(rules)};\n`);
console.log(`OpenUI renderer copied to public/vendor/openui/; prompt rules written to lib/openui-prompt.mjs (${rules.length} characters).`);
